package models

// StaticArchiveUpload is the response of the final chunk of a site archive
// upload (POST /applications/archive/uploads).
type StaticArchiveUpload struct {
	UploadID string `json:"upload_id"`
	Size     int64  `json:"size"`
	SHA      string `json:"sha"`
}

// StaticArchiveCreateRequest creates a static site application from an
// uploaded archive (POST /applications/archive).
type StaticArchiveCreateRequest struct {
	ProjectUUID        string  `json:"project_uuid"`
	ServerUUID         string  `json:"server_uuid"`
	EnvironmentName    string  `json:"environment_name,omitempty"`
	EnvironmentUUID    string  `json:"environment_uuid,omitempty"`
	DestinationUUID    string  `json:"destination_uuid,omitempty"`
	Name               string  `json:"name,omitempty"`
	Description        string  `json:"description,omitempty"`
	Domains            string  `json:"domains,omitempty"`
	AutogenerateDomain *bool   `json:"autogenerate_domain,omitempty"`
	IsSpa              *bool   `json:"is_spa,omitempty"`
	UploadID           *string `json:"upload_id,omitempty"`
	InstantDeploy      *bool   `json:"instant_deploy,omitempty"`
}

// StaticArchiveCreated is the 201 response of POST /applications/archive.
// Domains is the comma-separated list of the application URLs.
type StaticArchiveCreated struct {
	UUID           string `json:"uuid"`
	Domains        string `json:"domains"`
	DeploymentUUID string `json:"deployment_uuid"`
}

// StaticArchiveDeployRequest deploys a new archive to an existing archive
// application (POST /applications/{uuid}/archive).
type StaticArchiveDeployRequest struct {
	UploadID     string `json:"upload_id"`
	ForceRebuild *bool  `json:"force_rebuild,omitempty"`
}

// StaticArchiveDeployed is the 201 response of POST /applications/{uuid}/archive.
type StaticArchiveDeployed struct {
	DeploymentUUID string `json:"deployment_uuid"`
	SHA            string `json:"sha"`
	Domains        string `json:"domains"`
}
